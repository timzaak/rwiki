//! PostgreSQL 轨道版本化迁移（内联 DDL + 自管版本 runner）。
//!
//! 与 SQLite 轨道 `migration.rs` 内联 DDL 的项目先例一致；不使用
//! `sqlx::migrate!` 目录模式（sqlx 0.9 `MigrationSource` 仅有路径实现）。
//! PG 轨道为全新建库，无存量回填，schema 以最终形态直接建表。

use sqlx::PgPool;

/// V1：documents / chat_feedback / low_recall_records 及其索引。
const V1_DOCUMENTS_AND_RECORDS: &str = "\
CREATE TABLE IF NOT EXISTS documents (\
    id TEXT PRIMARY KEY,\
    file_name TEXT NOT NULL,\
    status TEXT NOT NULL DEFAULT 'processing',\
    row_count INTEGER NOT NULL DEFAULT 0,\
    error_message TEXT,\
    channel_id TEXT NOT NULL,\
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()\
);\
CREATE INDEX IF NOT EXISTS idx_documents_channel_id ON documents(channel_id);\
CREATE TABLE IF NOT EXISTS chat_feedback (\
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,\
    channel_id TEXT NOT NULL,\
    session_id TEXT NOT NULL,\
    message_id TEXT NOT NULL,\
    feedback TEXT NOT NULL CHECK (feedback IN ('like','dislike')),\
    user_message TEXT NOT NULL,\
    assistant_message TEXT NOT NULL,\
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),\
    UNIQUE (channel_id, session_id, message_id)\
);\
CREATE INDEX IF NOT EXISTS idx_chat_feedback_created_at ON chat_feedback(created_at DESC);\
CREATE INDEX IF NOT EXISTS idx_chat_feedback_feedback ON chat_feedback(feedback);\
CREATE INDEX IF NOT EXISTS idx_chat_feedback_channel_id ON chat_feedback(channel_id);\
CREATE TABLE IF NOT EXISTS low_recall_records (\
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,\
    session_id TEXT,\
    channel_id TEXT NOT NULL,\
    query TEXT NOT NULL,\
    top_score DOUBLE PRECISION,\
    result_count INTEGER NOT NULL DEFAULT 0,\
    sources TEXT NOT NULL DEFAULT '[]',\
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()\
);\
CREATE INDEX IF NOT EXISTS idx_low_recall_created_at ON low_recall_records(created_at DESC);\
CREATE INDEX IF NOT EXISTS idx_low_recall_top_score ON low_recall_records(top_score);\
CREATE INDEX IF NOT EXISTS idx_low_recall_channel_id ON low_recall_records(channel_id);";

/// V2：chunk_metadata（tokens_text + 生成列 fts）+ GIN 及二级索引。
const V2_CHUNK_METADATA: &str = "\
CREATE TABLE IF NOT EXISTS chunk_metadata (\
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,\
    document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,\
    chunk_id TEXT NOT NULL,\
    content TEXT NOT NULL,\
    title TEXT NOT NULL DEFAULT '',\
    locale TEXT,\
    link TEXT,\
    tags TEXT NOT NULL DEFAULT '',\
    section TEXT,\
    content_hash TEXT,\
    embedding_model TEXT,\
    page_id TEXT NOT NULL DEFAULT '',\
    sub_index BIGINT,\
    chunk_count BIGINT,\
    tokens_text TEXT NOT NULL DEFAULT '',\
    fts tsvector GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, tokens_text)) STORED\
);\
CREATE INDEX IF NOT EXISTS idx_chunk_metadata_document_id ON chunk_metadata(document_id);\
CREATE INDEX IF NOT EXISTS idx_chunk_metadata_content_hash ON chunk_metadata(content_hash);\
CREATE INDEX IF NOT EXISTS idx_chunk_metadata_page_sub ON chunk_metadata(page_id, sub_index);\
CREATE INDEX IF NOT EXISTS idx_chunk_metadata_fts ON chunk_metadata USING gin (fts);";

/// 有序迁移清单：下标 + 1 即版本号。
const MIGRATIONS: &[&str] = &[V1_DOCUMENTS_AND_RECORDS, V2_CHUNK_METADATA];

/// 逐条应用未执行的迁移：每条迁移在单事务内执行 DDL 并记录版本，幂等可重入。
pub async fn run_pending(pool: &PgPool) -> Result<(), sqlx::Error> {
    sqlx::query(
        "CREATE TABLE IF NOT EXISTS _pg_migrations (\
            version BIGINT PRIMARY KEY,\
            applied_at TIMESTAMPTZ NOT NULL DEFAULT now()\
        )",
    )
    .execute(pool)
    .await?;

    for (idx, ddl) in MIGRATIONS.iter().enumerate() {
        let version = (idx + 1) as i64;
        let applied: Option<i64> =
            sqlx::query_scalar("SELECT version FROM _pg_migrations WHERE version = $1")
                .bind(version)
                .fetch_optional(pool)
                .await?;
        if applied.is_some() {
            continue;
        }

        let mut tx = pool.begin().await?;
        // 版本化迁移为多语句 DDL 脚本，必须走 raw_sql（prepared 不接受多命令）
        sqlx::raw_sql(*ddl).execute(&mut *tx).await?;
        sqlx::query("INSERT INTO _pg_migrations (version) VALUES ($1)")
            .bind(version)
            .execute(&mut *tx)
            .await?;
        tx.commit().await?;
        tracing::info!(version, "PG migration applied");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    // Covers: 迁移清单为非空静态数组且有序（版本号由下标派生，禁止空清单/重复注册）。
    #[test]
    fn migrations_are_non_empty_and_ordered() {
        assert!(!MIGRATIONS.is_empty(), "PG 迁移清单不能为空");
        assert!(MIGRATIONS.len() >= 2, "V1/V2 基线迁移必须注册");
    }

    // Covers: DDL 常量包含关键对象（六表骨架的版本化部分），
    // 防止误删索引/约束后静默通过。
    #[test]
    fn migration_ddl_declares_expected_objects() {
        let all = format!("{}\n{}", V1_DOCUMENTS_AND_RECORDS, V2_CHUNK_METADATA);
        for expect in [
            "CREATE TABLE IF NOT EXISTS documents",
            "CREATE TABLE IF NOT EXISTS chat_feedback",
            "CREATE TABLE IF NOT EXISTS low_recall_records",
            "CREATE TABLE IF NOT EXISTS chunk_metadata",
            "to_tsvector('simple'::regconfig, tokens_text)",
            "USING gin (fts)",
            "ON DELETE CASCADE",
            "UNIQUE (channel_id, session_id, message_id)",
        ] {
            assert!(all.contains(expect), "PG 迁移 DDL 缺少声明对象: {expect}");
        }
    }
}
